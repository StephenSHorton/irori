// gen-models reads src/gen/bindings.ts (written by `cargo xtask bindings`)
// and writes src/gen/models.ts: every binding type re-exported, plus a
// factory per object type that fills what a caller leaves out with Go's
// zero values ("" , 0, false, [], null, a nested zero object), the way the
// Wails model constructors did. Only the samples and tests build models
// by hand; the gateways pass the host's JSON through as it is.
//
//   bun scripts/gen-models.ts           write src/gen/models.ts
//   bun scripts/gen-models.ts --check   fail if the committed file is stale

import { readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"

const root = resolve(import.meta.dir, "..")
const input = join(root, "src", "gen", "bindings.ts")
const out = join(root, "src", "gen", "models.ts")

type Field = { name: string; optional: boolean; type: string }
type Obj = { name: string; fields: Field[]; base: string[] }

export function parse(src: string): { objects: Obj[]; aliases: string[] } {
  const objects: Obj[] = []
  const aliases: string[] = []
  const re = /^export type (\w+) = ([\s\S]*?);\n(?=\n|\/\*|export|$)/gm
  for (const m of src.matchAll(re)) {
    const [, name, body] = m
    const obj = body.match(/^\{\n([\s\S]*?)\n\}((?:\s*&\s*\w+)*)$/)
    if (!obj) {
      aliases.push(name)
      continue
    }
    const fields: Field[] = []
    for (const line of obj[1].split("\n")) {
      const f = line.trim().match(/^(\w+)(\??): (.+?),?$/)
      if (f) fields.push({ name: f[1], optional: f[2] === "?", type: f[3] })
    }
    const base = obj[2]
      .split("&")
      .map((s) => s.trim())
      .filter(Boolean)
    objects.push({ name, fields, base })
  }
  return { objects, aliases }
}

function zero(type: string, objects: Set<string>): string {
  const t = type.trim()
  if (t.endsWith("| null")) return "null"
  if (t.endsWith("[]")) return "[]"
  if (t === "string") return '""'
  if (t === "number") return "0"
  if (t === "boolean") return "false"
  if (objects.has(t)) return `${t}()`
  if (t.startsWith("{") || t.startsWith("Record<")) return "{}"
  // A literal union (a Go string enum): Go's zero value is "".
  return '""'
}

export function generate(src: string): string {
  const { objects, aliases } = parse(src)
  const names = new Set(objects.map((o) => o.name))
  const lines = [
    "// Generated by scripts/gen-models.ts from src/gen/bindings.ts. DO NOT EDIT.",
    "/* eslint-disable */",
    "",
    'import type * as B from "./bindings"',
    "",
  ]
  for (const n of [...objects.map((o) => o.name), ...aliases].sort()) {
    lines.push(`export type ${n} = B.${n}`)
  }
  lines.push("")
  for (const o of [...objects].sort((a, b) => a.name.localeCompare(b.name))) {
    const parts = o.fields
      .filter((f) => !f.optional)
      .map((f) => `${JSON.stringify(f.name)}: ${zero(f.type, names)}`)
    const spread = o.base.map((b) => `...${b}()`)
    const body = [...spread, ...parts].join(", ")
    lines.push(
      `/** ${o.name} with Go's zero values for every field left out. */`,
      `export function ${o.name}(p: Partial<B.${o.name}> = {}): B.${o.name} {`,
      `  return { ${body}${body ? ", " : ""}...p } as B.${o.name}`,
      "}",
      ""
    )
  }
  return lines.join("\n")
}

if (import.meta.main) {
  const want = generate(readFileSync(input, "utf8").replace(/\r\n/g, "\n"))
  if (process.argv.includes("--check")) {
    const have = readFileSync(out, "utf8").replace(/\r\n/g, "\n")
    if (have !== want) {
      console.error("src/gen/models.ts is stale: run `bun scripts/gen-models.ts`")
      process.exit(1)
    }
  } else {
    writeFileSync(out, want)
  }
}
